package dev.n0png.fieldops.core.propagation

import java.io.ByteArrayOutputStream
import java.io.DataOutputStream
import java.nio.ByteBuffer
import java.security.MessageDigest
import java.security.SecureRandom
import javax.crypto.Cipher
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * CP-0009J authenticated V2 envelope crypto primitive (NO Android persistence).
 * Requires a caller-owned AES-256 key and fresh random nonce on EVERY write.
 * The entire visible header is authenticated as GCM AAD. No fallback to v1.
 * Ciphertext proves only file integrity under this key, NOT report provenance.
 */
object AuthenticatedArchiveEnvelopeV2 {
    private val MAGIC = "FTX1ENC2".toByteArray(Charsets.US_ASCII)
    const val VERSION = 2
    const val SUITE_AES_256_GCM = 1
    const val KEY_ID_BYTES = 16
    const val NONCE_BYTES = 12
    const val TAG_BYTES = 16
    const val HEADER_BYTES = 8 + 4 + 4 + KEY_ID_BYTES + NONCE_BYTES + 4
    const val MAX_ENCRYPTED_BYTES =
        PropagationArchiveStorageCodec.MAX_ENVELOPE_BYTES + 4096

    /** Caller must never intentionally repeat the nonce with the same key. */
    fun sealLegacyV1(
        legacyEnvelope: ByteArray,
        key: SecretKey,
        keyIdentifier: ByteArray,
        secureRandom: SecureRandom = SecureRandom(),
    ): ByteArray {
        require(key.algorithm.equals("AES", ignoreCase = true) &&
            (key.encoded == null || key.encoded.size == 32)) { "AES-256 key required" }
        require(keyIdentifier.size == KEY_ID_BYTES) { "Invalid key identifier" }
        // Never take untrusted bytes as authenticated simply because they have v1 magic.
        PropagationArchiveStorageCodec.decode(legacyEnvelope)
        // AndroidKeyStore keys with randomized encryption required reject
        // caller-provided GCM IVs. Initialize encryption first and capture
        // the unique IV generated by the cryptographic provider instead.
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.ENCRYPT_MODE, key, secureRandom)
        val nonce = cipher.iv
        check(nonce != null && nonce.size == NONCE_BYTES) {
            "AES-GCM provider did not generate a 96-bit nonce"
        }
        val cipherLength = legacyEnvelope.size + TAG_BYTES
        require(HEADER_BYTES + cipherLength <= MAX_ENCRYPTED_BYTES) {
            "Encrypted archive exceeds reserved size"
        }
        val headerOutput = ByteArrayOutputStream(HEADER_BYTES)
        DataOutputStream(headerOutput).use { out ->
            out.write(MAGIC)
            out.writeInt(VERSION)
            out.writeInt(SUITE_AES_256_GCM)
            out.write(keyIdentifier)
            out.write(nonce)
            out.writeInt(cipherLength)
        }
        val header = headerOutput.toByteArray()
        check(header.size == HEADER_BYTES)
        cipher.updateAAD(header)
        val encrypted = cipher.doFinal(legacyEnvelope)
        check(encrypted.size == cipherLength)
        return header + encrypted
    }

    /** Fails closed for wrong key ID, header changes, bad tag or invalid v1 receipts. */
    fun openLegacyV1(
        envelope: ByteArray,
        key: SecretKey,
        expectedKeyIdentifier: ByteArray,
    ): ByteArray {
        require(key.algorithm.equals("AES", ignoreCase = true) &&
            (key.encoded == null || key.encoded.size == 32)) { "AES-256 key required" }
        require(expectedKeyIdentifier.size == KEY_ID_BYTES) { "Invalid key identifier" }
        require(envelope.size in (HEADER_BYTES + TAG_BYTES + 1)..MAX_ENCRYPTED_BYTES) {
            "Truncated or oversized V2 envelope"
        }
        val header = envelope.copyOfRange(0, HEADER_BYTES)
        val buffer = ByteBuffer.wrap(header)
        val magic = ByteArray(MAGIC.size).also { buffer.get(it) }
        require(magic.contentEquals(MAGIC)) { "Unrecognized encrypted archive magic" }
        require(buffer.int == VERSION) { "Unsupported encrypted archive version" }
        require(buffer.int == SUITE_AES_256_GCM) { "Unsupported encrypted archive cipher suite" }
        val keyId = ByteArray(KEY_ID_BYTES).also { buffer.get(it) }
        require(MessageDigest.isEqual(keyId, expectedKeyIdentifier)) {
            "Encrypted archive key identifier mismatch"
        }
        val nonce = ByteArray(NONCE_BYTES).also { buffer.get(it) }
        val cipherLength = buffer.int
        require(cipherLength >= TAG_BYTES + 1 &&
            cipherLength <= PropagationArchiveStorageCodec.MAX_ENVELOPE_BYTES + TAG_BYTES &&
            HEADER_BYTES.toLong() + cipherLength.toLong() == envelope.size.toLong()) {
            "Invalid encrypted archive length or trailing bytes"
        }
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(TAG_BYTES * 8, nonce))
        cipher.updateAAD(header)
        val legacy = cipher.doFinal(envelope, HEADER_BYTES, cipherLength)
        PropagationArchiveStorageCodec.decode(legacy)
        return legacy
    }
}
